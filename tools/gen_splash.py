"""firmware/src/splash_data.h: the start picture for the FM-1's screen (splash.c), from assets/splash_240.png
(240 x 240, at most 16 colours, indexed: drawn by tools/splash_art.py, its flat version reduced to 16 colours).
Two pixels a byte, raw deflate with a 1 KiB window (firmware/src/inflate.c streams it), the palette in RGB565 as the
panel takes it (high byte first).
  python3 tools/gen_splash.py"""
import zlib
from pathlib import Path
from PIL import Image

SRC = Path(__file__).resolve().parents[1]
PNG = SRC / "assets" / "splash_240.png"


def image():
    """the picture: its pixels as indices 0..15 (the colours used, in order), and their colours"""
    im = Image.open(PNG)
    if im.size != (240, 240) or im.mode != "P":
        raise SystemExit(f"{PNG}: 240 x 240, indexed")
    d = list(im.getdata())
    used = sorted(set(d))
    if len(used) > 16:
        raise SystemExit(f"{PNG}: {len(used)} colours, at most 16")
    pal = im.getpalette()
    to = {u: k for k, u in enumerate(used)}
    return [to[x] for x in d], [tuple(pal[3 * u:3 * u + 3]) for u in used] + [(0, 0, 0)] * (16 - len(used))


def pixels():
    """two pixels a byte, the left one in the high nibble, row after row"""
    d = image()[0]
    return bytes((d[i] << 4) | d[i + 1] for i in range(0, len(d), 2))


def main():
    pal = image()[1]
    c = zlib.compressobj(9, zlib.DEFLATED, -10, 9)
    z = c.compress(pixels()) + c.flush()
    rgb = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in pal]
    lines = ["/* generated by tools/gen_splash.py from assets/splash_240.png: do not edit */", "#pragma once",
             "#include <stdint.h>", "/* the palette, RGB565 byte-swapped for the panel */",
             "static const uint16_t SPLASH_PAL[16] = {" + ", ".join(f"0x{((v >> 8) | (v << 8)) & 0xFFFF:04X}" for v in rgb) + "};",
             f"/* 240 x 240, 4 bits a pixel, raw deflate (1 KiB window): {len(z)} bytes */",
             f"static const uint8_t SPLASH_Z[{len(z)}] = {{"]
    for i in range(0, len(z), 24):
        lines.append("    " + ", ".join(str(b) for b in z[i:i + 24]) + ",")
    lines.append("};")
    (SRC / "firmware" / "src" / "splash_data.h").write_text("\n".join(lines) + "\n")
    print(f"gen_splash: {len(z)} bytes -> firmware/src/splash_data.h")


if __name__ == "__main__":
    main()
